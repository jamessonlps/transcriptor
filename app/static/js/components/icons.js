/**
 * Return the SVG markup for an icon by name. Use ``innerHTML`` to inject.
 * Unknown names return an empty string — callers can treat that as "no icon".
 *
 * @param {keyof typeof ICONS} name
 * @returns {string}
 */
export function icon(name) {
    return ICONS[name] ?? '';
}

/**
 * Convenience: create a detached DOM element pre-populated with an icon.
 * Useful when you don't want to use ``innerHTML`` for some reason (CSP, etc.).
 */
export function iconElement(name, { tag = 'span', className = '' } = {}) {
    const wrap = document.createElement(tag);
    if (className) wrap.className = className;
    wrap.innerHTML = icon(name);
    return wrap;
}

/**
 * Walk a DOM subtree and replace any ``<i data-icon="X"></i>`` (or
 * ``<span data-icon="X">``) placeholder with the matching SVG. Lets the
 * HTML templates stay free of inline SVG markup.
 *
 * @param {ParentNode} root
 */
export function hydrateIcons(root = document) {
    root.querySelectorAll('[data-icon]').forEach(node => {
        const name = node.dataset.icon;
        const svg = icon(name);
        if (svg) node.innerHTML = svg;
    });
}

